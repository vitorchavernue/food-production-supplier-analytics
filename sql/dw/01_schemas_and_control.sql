-- =====================================================================================
-- Data warehouse - schemas and control tables (PostgreSQL)
-- -------------------------------------------------------------------------------------
-- Layers:
--   stg   copy of what Apache Hop extracted from the ERP in this run (truncated every run)
--   dw    star schema: conformed dimensions and facts
--   etl   run log, watermarks (what was already read) and rejected records with reasons
--   dq    data quality results of every run (the release gate)
--   mart  views ready for Qlik Sense and ad hoc analysis
-- =====================================================================================

CREATE SCHEMA IF NOT EXISTS stg;
CREATE SCHEMA IF NOT EXISTS dw;
CREATE SCHEMA IF NOT EXISTS etl;
CREATE SCHEMA IF NOT EXISTS dq;
CREATE SCHEMA IF NOT EXISTS mart;

-- One row per execution of the Hop workflow: when it ran and how it ended
CREATE TABLE etl.run_log (
    run_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    started_at   TIMESTAMP NOT NULL,
    finished_at  TIMESTAMP,
    status       VARCHAR(20) NOT NULL,  -- running, passed, failed (quality gate), error
    PRIMARY KEY (run_id)
);

-- Last change already loaded from each ERP table. Hop reads only rows updated after it
-- (minus a 5 minute safety overlap, harmless because every load is idempotent).
CREATE TABLE etl.watermark (
    source_table     VARCHAR(40) NOT NULL,
    last_updated_at  TIMESTAMP NOT NULL,
    PRIMARY KEY (source_table)
);

