-- ERP rows that did not enter the warehouse, with the reason and the amount involved.
-- A rejected row leaves this table when the ERP fixes it and it loads successfully.
CREATE TABLE etl.rejected_record (
    run_id        BIGINT NOT NULL,
    source_table  VARCHAR(40) NOT NULL,
    source_key    BIGINT NOT NULL,
    reason        VARCHAR(200) NOT NULL,
    amount        NUMERIC(14, 2),  -- weight in kg of the rejected row (0 when it has none)
    rejected_at   TIMESTAMP NOT NULL
);

-- Result of every data quality check of every run. Critical checks are the release gate.
CREATE TABLE dq.check_result (
    run_id      BIGINT NOT NULL,
    check_name  VARCHAR(100) NOT NULL,
    severity    VARCHAR(10) NOT NULL,  -- critical (stops the release) or info
    expected    NUMERIC(18, 2),
    actual      NUMERIC(18, 2),
    passed      BOOLEAN NOT NULL,
    checked_at  TIMESTAMP NOT NULL
);
