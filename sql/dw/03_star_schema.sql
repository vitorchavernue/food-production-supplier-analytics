-- =====================================================================================
-- Star schema: conformed dimensions and four facts
-- -------------------------------------------------------------------------------------
-- Every dimension has an "Unknown" member with key -1, so a fact row is never lost when
-- a code is missing; a critical quality check makes sure there are none.
-- =====================================================================================

CREATE TABLE dw.dim_date (
    date_key     INTEGER NOT NULL,  -- yyyymmdd
    full_date    DATE NOT NULL,
    year         SMALLINT NOT NULL,
    quarter      SMALLINT NOT NULL,
    month        SMALLINT NOT NULL,
    month_name   VARCHAR(10) NOT NULL,
    year_month   CHAR(7) NOT NULL,   -- 2026-03
    day_of_week  SMALLINT NOT NULL,  -- 0 = Sunday
    is_weekend   BOOLEAN NOT NULL,
    is_summer    BOOLEAN NOT NULL,   -- December to March: heat stress season for live birds
    PRIMARY KEY (date_key)
);

CREATE TABLE dw.dim_plant (
    plant_key           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    plant_code          INTEGER NOT NULL,
    plant_name          VARCHAR(120) NOT NULL,
    city                VARCHAR(120) NOT NULL,
    state               CHAR(2) NOT NULL,
    region              VARCHAR(20) NOT NULL,
    capacity_birds_day  INTEGER NOT NULL,
    PRIMARY KEY (plant_key)
);

-- One row per farm (CNPJ). Farms registered twice in the ERP are merged here;
-- dw.supplier_code_map keeps every ERP code pointing to the right farm.
CREATE TABLE dw.dim_supplier (
    supplier_key       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    cnpj               CHAR(14) NOT NULL,
    legal_name         VARCHAR(200) NOT NULL,
    city               VARCHAR(120) NOT NULL,
    state              CHAR(2) NOT NULL,
    plant_code         INTEGER NOT NULL,
    distance_km        INTEGER NOT NULL,
    distance_band      VARCHAR(20) NOT NULL,  -- under 30 km, 30-60 km, 60-100 km, over 100 km
    integration_start  DATE NOT NULL,
    is_active          BOOLEAN NOT NULL,
    PRIMARY KEY (supplier_key)
);

CREATE TABLE dw.supplier_code_map (
    supplier_code  INTEGER NOT NULL,
    cnpj           CHAR(14) NOT NULL,
    PRIMARY KEY (supplier_code)
);

CREATE TABLE dw.dim_product (
    product_key     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    product_code    INTEGER NOT NULL,
    description     VARCHAR(160) NOT NULL,
    category        VARCHAR(40) NOT NULL,
    standard_yield  NUMERIC(5, 4) NOT NULL,
    PRIMARY KEY (product_key)
);

-- One row per truck of live birds received (or cancelled)
CREATE TABLE dw.fact_lot_receipt (
    lot_number      BIGINT NOT NULL,
    date_key        INTEGER NOT NULL,
    supplier_key    INTEGER NOT NULL,
    plant_key       INTEGER NOT NULL,
    status          VARCHAR(10) NOT NULL,  -- received or cancelled
    scheduled_at    TIMESTAMP NOT NULL,
    arrived_at      TIMESTAMP,
    delay_minutes   INTEGER,
    is_on_time      BOOLEAN,               -- arrived at most 60 minutes after the schedule
    birds           INTEGER,
    live_weight_kg  NUMERIC(12, 2),
    doa_birds       INTEGER,               -- dead on arrival
    condemned_kg    NUMERIC(10, 2),
    run_id          BIGINT NOT NULL,
    PRIMARY KEY (lot_number)
);

-- One row per production order: part of a lot turned into one product on one line
CREATE TABLE dw.fact_production (
    order_number      BIGINT NOT NULL,
    lot_number        BIGINT NOT NULL,
    date_key          INTEGER NOT NULL,
    plant_key         INTEGER NOT NULL,
    product_key       INTEGER NOT NULL,
    supplier_key      INTEGER NOT NULL,  -- the farm the birds came from (through the lot)
    line_number       SMALLINT NOT NULL,
    duration_minutes  INTEGER NOT NULL,
    planned_kg        NUMERIC(12, 2) NOT NULL,
    produced_kg       NUMERIC(12, 2) NOT NULL,
    run_id            BIGINT NOT NULL,
    PRIMARY KEY (order_number)
);

CREATE TABLE dw.fact_quality_inspection (
    inspection_number  BIGINT NOT NULL,
    order_number       BIGINT NOT NULL,
    date_key           INTEGER NOT NULL,
    plant_key          INTEGER NOT NULL,
    product_key        INTEGER NOT NULL,
    line_number        SMALLINT NOT NULL,
    sample_size        INTEGER NOT NULL,
    defects            INTEGER NOT NULL,
    is_approved        BOOLEAN NOT NULL,
    run_id             BIGINT NOT NULL,
    PRIMARY KEY (inspection_number)
);

CREATE TABLE dw.fact_line_stop (
    stop_number   BIGINT NOT NULL,
    date_key      INTEGER NOT NULL,
    plant_key     INTEGER NOT NULL,
    line_number   SMALLINT NOT NULL,
    minutes       INTEGER NOT NULL,
    reason_group  VARCHAR(40) NOT NULL,  -- standardized from the free text typed by operators
    run_id        BIGINT NOT NULL,
    PRIMARY KEY (stop_number)
);

